        private static string _lang = "en";
        private static readonly Dictionary<string, Dictionary<string, string>> Tables = BuildTables();

        public static string CurrentLang
        {
            get { return _lang; }
            set
            {
                if (!string.IsNullOrEmpty(value) && Tables.ContainsKey(value))
                    _lang = value;
                else
                    _lang = "en";
            }
        }

        public static int LangIndex(string code)
        {
            for (int i = 0; i < LangCodes.Length; i++)
                if (string.Equals(LangCodes[i], code, StringComparison.OrdinalIgnoreCase))
                    return i;
            return 1; // English fallback
        }

        public static string T(string key)
        {
            Dictionary<string, string> tbl;
            string val;
            if (Tables.TryGetValue(_lang, out tbl) && tbl.TryGetValue(key, out val))
                return val;
            if (Tables.TryGetValue("en", out tbl) && tbl.TryGetValue(key, out val))
                return val;
            return key;
        }

        public static string[] DragChoices()
        {
            return new[] { T("act_none"), T("act_ldrag"), T("act_rdrag"), T("act_mdrag") };
        }

        public static string[] ClickChoices()
